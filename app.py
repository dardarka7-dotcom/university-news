@app.route("/")
def index():
    selected_category = request.args.get("category", "Все новости")
    categories = ["Все новости"] + sorted({item["category"] for item in NEWS})
    if selected_category == "Все новости":
        visible_news = NEWS
    elif selected_category in categories:
        visible_news = [item for item in NEWS if item["category"] == selected_category]
    else:
        visible_news = []

    return render_template(
        "index.html",
        news=visible_news,
        categories=categories,
        selected_category=selected_category,
    )


@app.route("/news/<int:news_id>")
def news_detail(news_id):
    article = next((item for item in NEWS if item["id"] == news_id), None)
    if article is None:
        abort(404)
    return render_template("article.html", article=article)


